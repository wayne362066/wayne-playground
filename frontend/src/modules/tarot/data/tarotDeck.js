export const tarotDeck = [...majorArcana, ...minorArcana]

export function drawTarotCards(count = 3) {
  const pool = [...tarotDeck]
  const drawn = []

  while (drawn.length < count && pool.length) {
    const randomValues = new Uint32Array(2)
    crypto.getRandomValues(randomValues)
    const cardIndex = randomValues[0] % pool.length
    const [card] = pool.splice(cardIndex, 1)

    drawn.push({
      ...card,
      orientation: randomValues[1] % 2 === 0 ? 'upright' : 'reversed',
    })
  }

  return drawn
}
